export function haversineDistance(lat1, lon1, lat2, lon2) {
  const R = 6371; // Earth's radius in km
  const dLat = (lat2 - lat1) * Math.PI / 180;
  const dLon = (lon2 - lon1) * Math.PI / 180;
  const a =
    Math.sin(dLat / 2) * Math.sin(dLat / 2) +
    Math.cos(lat1 * Math.PI / 180) * Math.cos(lat2 * Math.PI / 180) *
    Math.sin(dLon / 2) * Math.sin(dLon / 2);
  const c = 2 * Math.atan2(Math.sqrt(a), Math.sqrt(1 - a));
  return R * c;
}

export function findNearestCity(lat, lon) {
  if (!lat || !lon) return DEFAULT_LOCATION;
  let nearest = INDIAN_CITIES[0];
  let minDistance = Infinity;

  for (const item of INDIAN_CITIES) {
    const dist = haversineDistance(lat, lon, item.latitude, item.longitude);
    if (dist < minDistance) {
      minDistance = dist;
      nearest = item;
    }
  }

  return nearest;
}

export function findCityByName(query) {
  if (!query) return null;
  const q = query.trim().toLowerCase();
  return INDIAN_CITIES.find(c => c.city.toLowerCase() === q) ||
         INDIAN_CITIES.find(c => c.city.toLowerCase().includes(q)) || null;
}
