async def seed_demo_stories():
    print("==================================================")
    print("ATMOS 100 DEMO STORIES DATABASE SEEDING")
    print("==================================================")

    now = datetime.now(timezone.utc).replace(tzinfo=None)
    inserted_count = 0
    updated_count = 0

    async with async_session_factory() as session:
        for item in DEMO_STORIES_DATA:
            idx = item["index"]
            source_id = f"demo-story-{idx:03d}"
            
            # Days offset to spread published dates across past 30 days
            days_ago = (100 - idx) % 25
            pub_time = now - timedelta(days=days_ago, hours=(idx % 12))

            img_url = item["image_url"]
            photos_list = [img_url]
            media_list = [
                {
                    "type": "image",
                    "url": img_url,
                    "thumbnail_url": img_url,
                    "caption": item["title"],
                    "credit": item.get("image_credit"),
                    "credit_url": item.get("image_credit_url"),
                    "source": "Unsplash",
                }
            ]

            metadata_dict = {
                "is_static": True,
                "is_demo": True,
                "data_type": "DEMO",
                "source_type": "STATIC_DEMO",
                "category": item["category"],
                "tags": item.get("tags", []),
                "image_url": img_url,
                "image_source": "Unsplash",
                "image_credit": item.get("image_credit"),
                "image_credit_url": item.get("image_credit_url"),
                "source_name": item["source_name"],
                "confidence_score": 0.95,
                "is_video": item["source"] == EventSource.YOUTUBE,
            }

            # Check if record already exists by source_id
            stmt = select(WeatherEvent).where(WeatherEvent.source_id == source_id)
            result = await session.execute(stmt)
            existing = result.scalar_one_or_none()

            if existing:
                # Update existing record
                existing.title = item["title"]
                existing.description = item["description"]
                existing.event_type = item["event_type"]
                existing.severity = item["severity"]
                existing.source = item["source"]
                existing.city = item["city"]
                existing.state = item["state"]
                existing.latitude = item["lat"]
                existing.longitude = item["lon"]
                existing.photos = photos_list
                existing.videos = []
                existing.metadata_ = metadata_dict
                existing.verification_status = VerificationStatus.VERIFIED
                existing.reported_at = pub_time
                existing.updated_at = now
                updated_count += 1
            else:
                # Insert new record
                db_event = WeatherEvent(
                    title=item["title"],
                    description=item["description"],
                    event_type=item["event_type"],
                    severity=item["severity"],
                    source=item["source"],
                    source_url=None,
                    source_id=source_id,
                    city=item["city"],
                    state=item["state"],
                    latitude=item["lat"],
                    longitude=item["lon"],
                    photos=photos_list,
                    videos=[],
                    metadata_=metadata_dict,
                    verification_status=VerificationStatus.VERIFIED,
                    is_fake=False,
                    fake_confidence=0.0,
                    category_confidence=0.95,
                    created_at=pub_time,
                    updated_at=now,
                    reported_at=pub_time,
                )
                session.add(db_event)
                inserted_count += 1

        await session.commit()

    print(f"\nSeeding Complete!")
    print(f"-> Inserted: {inserted_count} new demo stories")
    print(f"-> Updated:  {updated_count} existing demo stories")
    print(f"-> Total Managed: {inserted_count + updated_count}")


if __name__ == "__main__":
    asyncio.run(seed_demo_stories())
